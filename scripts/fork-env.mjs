#!/usr/bin/env node
// FORK — generate the three .env files of a brand from one input file.
//
//   npm run fork:env                 # reads ./fork.env
//   npm run fork:env -- other.env    # another input file
//   npm run fork:env -- --dry-run    # print what would change, write nothing
//
// Templates are the tracked .env.example files, so new upstream variables show
// up automatically. `YOUR_…` placeholders become empty values. Existing .env
// files are backed up (.env.bak-<timestamp>) and their secrets are reused.
// See FORK-README §11.

import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const inputPath = resolve(ROOT, args.find((a) => !a.startsWith('--')) || 'fork.env');

const TARGETS = {
  FE: { example: '.env.example', output: '.env' },
  API: { example: 'API/Mainapi/.env.example', output: 'API/Mainapi/.env' },
  PROXY: { example: 'API/proxiesembed/.env.example', output: 'API/proxiesembed/.env' },
};

// ── .env parsing (KEY=value, optional quotes, inline " # comment") ──────────
function parseValue(raw) {
  const value = raw.trim();
  const quoted = value.match(/^(["'])(.*)\1(\s+#.*)?$/);
  if (quoted) return quoted[2];
  return value.replace(/\s+#.*$/, '').replace(/^#.*$/, '').trim();
}

function parseEnv(text) {
  const env = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/);
    if (m) env[m[1]] = parseValue(m[2]);
  }
  return env;
}

const readEnv = (path) => (existsSync(path) ? parseEnv(readFileSync(path, 'utf8')) : {});
const isPlaceholder = (v) => !v || /^YOUR_/.test(v);

// Quotes are taken literally by Node dotenv, python-dotenv and Vite alike only
// when nothing needs escaping: "…" by default, '…' when the value contains ".
function formatValue(value, key = '') {
  const v = String(value ?? '');
  if (v === '' || /^[A-Za-z0-9_./:,@%+=*?&;~-]*$/.test(v)) return v;
  if (/[\r\n]/.test(v) || (v.includes('"') && v.includes("'"))) {
    throw new Error(`${key}: value cannot contain a line break or both kinds of quotes`);
  }
  return v.includes('"') ? `'${v}'` : `"${v}"`;
}

// Rewrite a template: overridden keys get their value (inline comment kept),
// placeholders are emptied, unknown overrides are appended at the end.
function render(templateText, overrides) {
  const pending = new Map(Object.entries(overrides));
  const lines = templateText.split(/\r?\n/).map((line) => {
    const m = line.match(/^(\s*)([A-Za-z_][A-Za-z0-9_]*)(\s*=)(.*)$/);
    if (!m) return line;
    const [, indent, key, eq, rest] = m;
    const comment = (rest.match(/\s+#.*$/) || [''])[0];
    if (pending.has(key)) {
      const value = pending.get(key);
      pending.delete(key);
      return `${indent}${key}${eq}${formatValue(value, key)}${comment}`;
    }
    return isPlaceholder(parseValue(rest)) && /YOUR_/.test(rest) ? `${indent}${key}${eq}${comment}` : line;
  });
  if (pending.size) {
    lines.push('', '# FORK — generated by scripts/fork-env.mjs');
    for (const [key, value] of pending) lines.push(`${key}=${formatValue(value, key)}`);
  }
  return lines.join('\n').replace(/\n*$/, '\n');
}

// ── Input ───────────────────────────────────────────────────────────────────
if (!existsSync(inputPath)) {
  console.error(`✖ ${relative(ROOT, inputPath)} not found. Copy fork.env.example to fork.env and fill it in.`);
  process.exit(1);
}
const input = readEnv(inputPath);
const get = (key, fallback = '') => (input[key] ?? '').trim() || fallback;

const domain = get('SITE_DOMAIN').replace(/^https?:\/\//, '').replace(/\/.*$/, '').toLowerCase();
const missing = ['SITE_DOMAIN', 'TMDB_API_KEY', 'DB_USER', 'DB_PASSWORD'].filter((k) => !get(k));
if (missing.length) {
  console.error(`✖ Missing in ${relative(ROOT, inputPath)}: ${missing.join(', ')}`);
  process.exit(1);
}

const siteUrl = `https://${domain}`;
const apiUrl = get('API_URL', siteUrl).replace(/\/+$/, '');
const proxyUrl = get('PROXY_URL', siteUrl).replace(/\/+$/, '');
const mainapiPort = get('MAINAPI_PORT', '25565');
const proxyPort = get('PROXIESEMBED_PORT', '25569');
const allowedDomains = [domain, ...get('EXTRA_DOMAINS').split(',').map((d) => d.trim()).filter(Boolean)];

// Secrets: input > existing Main API .env > existing proxiesembed .env > new.
const existingApi = readEnv(join(ROOT, TARGETS.API.output));
const existingProxy = readEnv(join(ROOT, TARGETS.PROXY.output));
const generated = [];
function secret(key, bytes = 32) {
  const found = [input[key], existingApi[key], existingProxy[key]].find((v) => !isPlaceholder(v));
  if (found) return found;
  generated.push(key);
  return randomBytes(bytes).toString('hex');
}
const secrets = {
  JWT_SECRET: secret('JWT_SECRET'),
  MEDIA_SIGNING_SECRET: secret('MEDIA_SIGNING_SECRET'),
  INTERNAL_API_KEY: secret('INTERNAL_API_KEY'),
  TURNSTILE_IP_SALT: secret('TURNSTILE_IP_SALT', 16),
};

const db = {
  DB_HOST: get('DB_HOST', '127.0.0.1'),
  DB_PORT: get('DB_PORT', '3306'),
  DB_USER: get('DB_USER'),
  DB_PASSWORD: get('DB_PASSWORD'),
  DB_NAME: get('DB_NAME', 'movix'),
};

const overrides = {
  FE: {
    VITE_MAIN_API: apiUrl,
    VITE_SITE_URL: siteUrl,
    VITE_PROXIES_EMBED_API: proxyUrl,
    VITE_TMDB_API_KEY: get('TMDB_API_KEY'),
    VITE_WATCHPARTY_API: '',
    VITE_TURNSTILE_SITE_KEY: get('TURNSTILE_SITE_KEY'),
    VITE_TURNSTILE_INVISIBLE_SITEKEY: get('TURNSTILE_INVISIBLE_SITE_KEY'),
    VITE_DEFAULT_MIRRORS: get('DEFAULT_MIRRORS', domain),
    VITE_MIRRORS_CONFIG_URL: get('MIRRORS_CONFIG_URL'),
  },
  API: {
    NODE_ENV: 'production',
    PORT: mainapiPort,
    NUM_WORKERS: get('NUM_WORKERS', '4'),
    FRONTEND_BASE_URL: siteUrl,
    PUBLIC_API_BASE: apiUrl,
    ALLOWED_DOMAINS: allowedDomains.join(','),
    ...db,
    REDIS_HOST: get('REDIS_HOST', '127.0.0.1'),
    REDIS_PORT: get('REDIS_PORT', '6379'),
    REDIS_PASSWORD: get('REDIS_PASSWORD'),
    TMDB_API_KEY: get('TMDB_API_KEY'),
    TURNSTILE_SECRET_KEY: get('TURNSTILE_SECRET_KEY'),
    TURNSTILE_INVISIBLE_SECRETKEY: get('TURNSTILE_INVISIBLE_SECRET_KEY'),
    JWT_SECRET: secrets.JWT_SECRET,
    TURNSTILE_IP_SALT: secrets.TURNSTILE_IP_SALT,
    MEDIA_SIGNING_SECRET: secrets.MEDIA_SIGNING_SECRET,
    MEDIA_SIGNATURE_TTL: '43200',
    INTERNAL_API_KEY: secrets.INTERNAL_API_KEY,
    PROXIESEMBED_PUBLIC_URL: proxyUrl,
    PROXIESEMBED_INTERNAL_URL: `http://127.0.0.1:${proxyPort}`,
    PROXY_SERVER_URL: `http://127.0.0.1:${proxyPort}/proxy`,
    IPTV_STREAM_PROXY: `http://127.0.0.1:${proxyPort}/proxy`,
    SCRAPE_USE_PROXY: 'false',
    WIFLIX_FREE_PROXY_ENABLED: 'false',
    // Upstream values that do not belong to a clone.
    MAINAPI_PROBE_DISCORD_USER_ID: '',
    VIP_PAYGATE_CALLBACK_BASE_URL: '',
    VIP_PAYBLIS_STORE_NAME: get('SITE_NAME', domain),
  },
  PROXY: {
    PORT: proxyPort,
    PROXY_BASE: proxyUrl,
    ...db,
    MEDIA_SIGNING_SECRET: secrets.MEDIA_SIGNING_SECRET,
    MEDIA_SIGNATURE_TTL: '43200',
    INTERNAL_API_KEY: secrets.INTERNAL_API_KEY,
  },
};

// FE_ / API_ / PROXY_ pass-through (API_URL is a layout key, not a pass-through).
for (const [key, value] of Object.entries(input)) {
  const m = key.match(/^(FE|API|PROXY)_(.+)$/);
  if (!m || key === 'API_URL' || key === 'PROXY_URL') continue;
  overrides[m[1]][m[2]] = value;
}

const feDollar = Object.entries(overrides.FE).filter(([, v]) => String(v).includes('$'));
if (feDollar.length) {
  console.warn(`⚠ Vite expands "$" in .env values: check ${feDollar.map(([k]) => k).join(', ')}`);
}

// ── Write ───────────────────────────────────────────────────────────────────
const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\..*$/, '').replace('T', '-');
for (const [name, target] of Object.entries(TARGETS)) {
  const examplePath = join(ROOT, target.example);
  const outputPath = join(ROOT, target.output);
  const text = render(readFileSync(examplePath, 'utf8'), overrides[name]);
  if (dryRun) {
    console.log(`\n── ${target.output} (dry run) ──`);
    for (const [key, value] of Object.entries(overrides[name])) {
      const shown = /SECRET|KEY|PASSWORD|SALT/.test(key) && value ? '••••' : value;
      console.log(`${key}=${shown}`);
    }
    continue;
  }
  if (existsSync(outputPath)) {
    const backup = `${outputPath}.bak-${stamp}`;
    copyFileSync(outputPath, backup);
    console.log(`↺ backup  ${relative(ROOT, backup)}`);
  }
  writeFileSync(outputPath, text, { mode: 0o600 });
  console.log(`✔ wrote   ${target.output}`);
}

console.log(`
Brand: ${domain}
  site   ${siteUrl}
  API    ${apiUrl}   (Main API → 127.0.0.1:${mainapiPort})
  proxy  ${proxyUrl}   (proxiesembed → 127.0.0.1:${proxyPort})
  CORS   ${allowedDomains.join(', ')}
Secrets ${generated.length ? `generated: ${generated.join(', ')}` : 'kept from the existing .env files'}${
  get('MIRRORS_CONFIG_URL') ? '' : `\nMirrors: no remote list, fallback = ${overrides.FE.VITE_DEFAULT_MIRRORS}`}

Next: src/config/branding.ts (name, logo, FEATURES), then npm run build — see FORK-README §11.`);
